function resolveAdminLocale(locale?: string): AdminLocale {
  if (!locale) return "en";
  const normalized = locale.trim().toLowerCase().replace(/_/g, "-");
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
  if (normalized === "es" || normalized.startsWith("es-")) return "es";
  if (normalized === "pt" || normalized.startsWith("pt-")) return "pt";
  if (normalized === "fr" || normalized.startsWith("fr-")) return "fr";
  return "en";
}

/** Admin UI copy only; never changes PageDocument.settings.locale or block contents. */
export function createAdminI18n(locale?: string) {
  const resolvedLocale = resolveAdminLocale(locale);
  return {
    locale: resolvedLocale,
    t: (key: AdminMessageKey, values?: AdminMessageValues): string => {
      const message = messages[resolvedLocale][key] ?? english[key];
      return message.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
        values?.[name] === undefined ? placeholder : String(values[name]));
    }
  };
}
